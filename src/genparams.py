#!/usr/bin/env python3
"""Generate ECT group parameters (p, q, g) for a target identifier capacity.

The scheme needs a cyclic group of order q^h inside Z_p^*, so we require
q^h | p-1.  Capacity is the largest N with r^N < q, and r must exceed the
per-depth multiplicity bound 2^(h-1), so r = 2^(h-1)+1.

Emits the P_STR / G_STR / Q_STR decimal literals for params.h.
"""
import random
import sys

H = 10
R = (1 << (H - 1)) + 1          # 513
TARGET_N = 28                    # identifier capacity
Q_BITS = 257                     # q >= 2^(2*lambda) for lambda = 128
P_BITS = 3072                    # DL security of Z_p^* at lambda = 128

SMALL_PRIMES = []
def _sieve(limit):
    s = bytearray([1]) * limit
    s[0:2] = b"\x00\x00"
    for i in range(2, int(limit ** 0.5) + 1):
        if s[i]:
            s[i * i::i] = bytearray(len(s[i * i::i]))
    return [i for i, v in enumerate(s) if v]
SMALL_PRIMES = _sieve(200000)


def is_probable_prime(n, rounds=12):
    if n < 2:
        return False
    for sp in SMALL_PRIMES[:200]:
        if n % sp == 0:
            return n == sp
    d = n - 1
    s = 0
    while d % 2 == 0:
        d //= 2
        s += 1
    for _ in range(rounds):
        a = random.randrange(2, n - 1)
        x = pow(a, d, n)
        if x == 1 or x == n - 1:
            continue
        for _ in range(s - 1):
            x = x * x % n
            if x == n - 1:
                break
        else:
            return False
    return True


def gen_q():
    lo = max(R ** TARGET_N, 1 << (Q_BITS - 1))  # need q > r^N and q >= 2^(2*lambda)
    hi = R ** (TARGET_N + 1)    # capacity ceiling: need q < r^(N+1)
    print(f"[q] searching {Q_BITS}-bit prime in (r^{TARGET_N}, r^{TARGET_N+1})",
          flush=True)
    tried = 0
    while True:
        cand = random.getrandbits(Q_BITS) | (1 << (Q_BITS - 1)) | 1
        if not (lo < cand < hi):
            continue
        tried += 1
        if is_probable_prime(cand):
            print(f"[q] found after {tried} candidates, {cand.bit_length()} bits",
                  flush=True)
            return cand


def gen_p(q):
    """Smallest even c with p = c*q^H + 1 prime and |p| = P_BITS."""
    qh = q ** H
    print(f"[p] q^{H} is {qh.bit_length()} bits; searching cofactor c", flush=True)
    # Precompute q^H mod s for cheap sieving of candidates.
    resid = [(s, qh % s) for s in SMALL_PRIMES if s > 2]
    c = ((1 << (P_BITS - 1)) // qh + 2) & ~1
    tested = 0
    while True:
        # cheap composite rejection before the expensive Miller-Rabin
        skip = False
        for s, qr in resid:
            if (c * qr + 1) % s == 0:
                skip = True
                break
        if not skip:
            p = c * qh + 1
            tested += 1
            if tested % 25 == 0:
                print(f"[p]   {tested} full tests, c={c}", flush=True)
            if is_probable_prime(p):
                print(f"[p] found c={c}, p is {p.bit_length()} bits "
                      f"({tested} full tests)", flush=True)
                return p, c, qh
        c += 2


def gen_g(p, c, q, qh):
    """g of order exactly q^H: take x^c and reject if g^(q^(H-1)) == 1."""
    q_h1 = q ** (H - 1)
    while True:
        x = random.randrange(2, p - 1)
        g = pow(x, c, p)
        if g == 1:
            continue
        if pow(g, q_h1, p) == 1:
            continue                       # order divides q^(H-1), reject
        assert pow(g, qh, p) == 1
        print(f"[g] found, {g.bit_length()} bits", flush=True)
        return g


def main():
    random.seed()
    q = gen_q()
    p, c, qh = gen_p(q)
    g = gen_g(p, c, q, qh)

    # capacity check
    n = 0
    while R ** (n + 1) < q:
        n += 1
    print(f"\n[check] capacity floor(log_r q) = {n}  (target {TARGET_N})")
    print(f"[check] q^H | p-1              : {(p - 1) % qh == 0}")
    print(f"[check] g^(q^H) == 1           : {pow(g, qh, p) == 1}")
    print(f"[check] g^(q^(H-1)) != 1       : {pow(g, q ** (H - 1), p) != 1}")
    print(f"[check] |p| = {p.bit_length()}  |q| = {q.bit_length()}  "
          f"tag = 2|p| = {2 * p.bit_length() / 8 / 1024:.2f} KB")

    with open("params_generated.h", "w") as f:
        f.write(f"/* generated by genparams.py: capacity {n}, h={H}, r={R} */\n")
        f.write(f'#define P_STR "{p}"\n\n')
        f.write(f'#define G_STR "{g}"\n\n')
        f.write(f'#define Q_STR "{q}"\n')
    print("\nwrote params_generated.h", flush=True)


if __name__ == "__main__":
    sys.exit(main())
